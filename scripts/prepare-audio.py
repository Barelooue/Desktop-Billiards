"""Prepare the licensed source recordings; runtime needs no download or decoder."""
from pathlib import Path
import base64
import json
import subprocess
import wave
import numpy as np

root = Path(__file__).resolve().parent.parent
folder = root / 'assets/audio'
samples = {}
rate = 44100
for name in ['ball', 'pocket']:
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(folder / f'{name}-original.mp3'),
                                  '-ac', '1', '-ar', str(rate), '-af', 'highpass=f=90', '-f', 'f32le', '-'])
    data = np.frombuffer(raw, dtype='<f4').copy()
    peak = float(np.max(np.abs(data)))
    indices = np.flatnonzero(np.abs(data) > peak * .015)
    start = max(0, int(indices[0]) - int(rate * .001))
    data = data[start:]
    data *= .88 / np.max(np.abs(data))
    fade_in, fade_out = int(rate * .0004), int(rate * .012)
    data[:fade_in] *= np.linspace(0, 1, fade_in)
    data[-fade_out:] *= np.linspace(1, 0, fade_out)
    pcm = (data * 32767).round().astype('<i2').tobytes()
    with wave.open(str(folder / f'{name}.wav'), 'wb') as output:
        output.setparams((1, 2, rate, 0, 'NONE', 'not compressed'))
        output.writeframes(pcm)
    samples[name] = {'sampleRate': rate, 'pcm': base64.b64encode(pcm).decode()}
    print(f'{name}: {len(data)/rate:.3f}s, peak {np.max(np.abs(data)):.3f}')
(root / 'src/audio-samples.js').write_text('// Generated by scripts/prepare-audio.py; credits: assets/audio/CREDITS.txt\n'
                                         + 'export const AUDIO_SAMPLES=' + json.dumps(samples, separators=(',', ':')) + ';\n', encoding='utf-8')
